import { CHUNK, World } from '../world/world';
import { DIRS, Dir } from '../assets/models';
import type { Baked, BlockModels, PQuad, RGB } from '../render/blockModels';

/**
 * Build file. Chunks are run-length encoded as flat [count, paletteId, count, paletteId, ...].
 * v2 adds optional `baked` geometry so a viewer without the Minecraft jar can draw the shapes.
 */
export interface BuildFileV1 {
  format: 'mc-build-visualizer';
  version: 1 | 2;
  name: string;
  palette: string[];
  chunks: Record<string, number[]>;
  /** Sign text: "x,y,z" → 4 front lines. */
  texts?: Record<string, string[]>;
  /** sprites: [name, avg color hex]; states: palette index → quads, each QUAD_LEN numbers (see encodeQuad). */
  baked?: { sprites: [string, number][]; states: Record<string, number[][]> };
}

const DIR_LIST = Object.keys(DIRS) as Dir[];
export const MAX_LINE = 90;
const QUAD_LEN = 26;
const r4 = (v: number) => Math.round(v * 1e4) / 1e4;
const toHex = (c: RGB) => c.reduce((h, v) => (h << 8) | Math.round(Math.min(1, Math.max(0, v)) * 255), 0);

/** [12 pos, 8 uv, sprite index (-1 none), r, g, b, forceTranslucent 0/1, cull dir index (-1 none)] */
function encodeQuad(q: PQuad, spriteIndex: (s: string) => number): number[] {
  return [...q.pos.map(r4), ...q.uv.map(r4), q.sprite ? spriteIndex(q.sprite) : -1, ...q.color.map((c) => r4(c)),
    Number(q.forceTranslucent), q.cull ? DIR_LIST.indexOf(q.cull) : -1];
}

/** Geometry for every blockstate in the build, from the models currently loaded. */
function bakeAll(palette: string[], models: BlockModels): BuildFileV1['baked'] {
  const sprites: [string, number][] = [];
  const index = new Map<string, number>();
  const spriteIndex = (s: string) => {
    let i = index.get(s);
    if (i === undefined) {
      index.set(s, (i = sprites.length));
      sprites.push([s, toHex(models.spriteColor(s) ?? [1, 0, 1])]);
    }
    return i;
  };
  const states: Record<string, number[][]> = {};
  palette.forEach((state, i) => {
    if (i === 0 || /^minecraft:(water|lava)\b/.test(state)) return; // fluids are generated by the viewer
    states[i] = models.portable(state).map((q) => encodeQuad(q, spriteIndex));
  });
  return { sprites, states };
}

export function serialize(world: World, name: string, models?: BlockModels): BuildFileV1 {
  // compact the palette to ids actually in use
  const remap = new Map<number, number>([[0, 0]]);
  const palette = [world.palette[0]];
  const chunks: Record<string, number[]> = {};
  for (const [key, data] of world.chunks) {
    const rle: number[] = [];
    let run = 0, prev = -1;
    for (const raw of data) {
      let id = remap.get(raw);
      if (id === undefined) {
        id = palette.length;
        palette.push(world.palette[raw]);
        remap.set(raw, id);
      }
      if (id === prev) run++;
      else {
        if (run) rle.push(run, prev);
        prev = id;
        run = 1;
      }
    }
    rle.push(run, prev);
    chunks[key] = rle;
  }
  return {
    format: 'mc-build-visualizer', version: 2, name, palette, chunks,
    ...(world.texts.size && { texts: Object.fromEntries(world.texts) }),
    ...(models && { baked: bakeAll(palette, models) }),
  };
}

function decodeBaked(b: any, palette: string[]): Baked {
  if (typeof b !== 'object' || !Array.isArray(b.sprites) || typeof b.states !== 'object' || !b.states) throw new Error('Bad baked geometry');
  const names: string[] = [];
  const spriteColors = new Map<string, RGB>();
  for (const e of b.sprites) {
    if (!Array.isArray(e) || typeof e[0] !== 'string' || !/^[a-z0-9_/.-]{1,128}$/.test(e[0]) || !Number.isInteger(e[1])) throw new Error('Bad sprite entry');
    names.push(e[0]);
    spriteColors.set(e[0], [((e[1] >> 16) & 255) / 255, ((e[1] >> 8) & 255) / 255, (e[1] & 255) / 255]);
  }
  const states = new Map<string, PQuad[]>();
  for (const [key, quads] of Object.entries<any>(b.states)) {
    const i = Number(key);
    if (!Number.isInteger(i) || i <= 0 || i >= palette.length || !Array.isArray(quads) || quads.length > 4096) throw new Error('Bad baked state');
    states.set(palette[i], quads.map((q: any) => {
      if (!Array.isArray(q) || q.length !== QUAD_LEN || !q.every((v: unknown) => typeof v === 'number' && Number.isFinite(v))) throw new Error('Bad baked quad');
      const s = q[20], cull = q[25];
      if (!Number.isInteger(s) || !Number.isInteger(cull) || s < -1 || s >= names.length || cull < -1 || cull > 5) throw new Error('Bad baked quad');
      return { pos: q.slice(0, 12), uv: q.slice(12, 20), sprite: s >= 0 ? names[s] : null, color: q.slice(21, 24) as RGB, forceTranslucent: q[24] === 1, cull: cull >= 0 ? DIR_LIST[cull] : null };
    }));
  }
  return { states, spriteColors };
}

/** Validates untrusted input (imported files, ?build= URLs) before touching the world. */
export function deserialize(json: unknown, world: World): { name: string; baked?: Baked } {
  const f = json as BuildFileV1;
  if (!f || f.format !== 'mc-build-visualizer') throw new Error('Not an mc-build-visualizer file');
  if (f.version !== 1 && f.version !== 2) throw new Error(`Unsupported build file version: ${f.version}`);
  if (!Array.isArray(f.palette) || !f.palette.every((s) => typeof s === 'string')) throw new Error('Bad palette');
  if (typeof f.chunks !== 'object' || f.chunks === null) throw new Error('Bad chunks');
  const baked = f.baked === undefined ? undefined : decodeBaked(f.baked, f.palette);
  const texts = Object.entries(f.texts ?? {});
  for (const [k, lines] of texts)
    if (!/^-?\d+,-?\d+,-?\d+$/.test(k) || !Array.isArray(lines) || lines.length > 4 || !lines.every((l) => typeof l === 'string' && l.length <= MAX_LINE))
      throw new Error('Bad sign text');

  const size = CHUNK ** 3;
  const decoded = new Map<string, Uint16Array>();
  for (const [key, rle] of Object.entries(f.chunks)) {
    if (!/^-?\d+,-?\d+,-?\d+$/.test(key) || !Array.isArray(rle)) throw new Error(`Bad chunk ${key}`);
    const out = new Uint16Array(size);
    let i = 0;
    for (let r = 0; r < rle.length; r += 2) {
      const count = rle[r], id = rle[r + 1];
      if (!Number.isInteger(count) || !Number.isInteger(id) || id < 0 || id >= f.palette.length || i + count > size)
        throw new Error(`Corrupt chunk ${key}`);
      out.fill(id, i, i + count);
      i += count;
    }
    if (i !== size) throw new Error(`Corrupt chunk ${key}`);
    decoded.set(key, out);
  }

  world.clear();
  const ids = f.palette.map((s) => world.idOf(s));
  for (const [key, data] of decoded) {
    for (let i = 0; i < data.length; i++) data[i] = ids[data[i]];
    if (data.some((v) => v !== 0)) world.chunks.set(key, data);
  }
  for (const [k, lines] of texts) world.texts.set(k, lines);
  world.onChange(new Set(world.chunks.keys()));
  return { name: typeof f.name === 'string' ? f.name.slice(0, 200) : 'Imported build', baked };
}
